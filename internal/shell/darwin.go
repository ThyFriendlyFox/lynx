package shell

import (
	"os"
	"path/filepath"
	"strings"
)

// darwinServicePath is where macOS looks for Quick Actions of one person.
func darwinServicePath() string {
	home, err := os.UserHomeDir()
	if err != nil {
		home = "."
	}
	return filepath.Join(home, "Library", "Services", MenuTitle+".workflow")
}

// installDarwin writes a Quick Action. Finder shows it when a person right
// clicks a folder, under "Quick Actions".
func installDarwin(exe string) (string, error) {
	root := darwinServicePath()
	contents := filepath.Join(root, "Contents")
	if err := os.MkdirAll(contents, 0o755); err != nil {
		return "", err
	}
	if err := os.WriteFile(filepath.Join(contents, "Info.plist"), []byte(darwinInfoPlist), 0o644); err != nil {
		return "", err
	}
	script := strings.ReplaceAll(darwinScript, "{{EXE}}", exe)
	doc := strings.ReplaceAll(darwinWorkflow, "{{SCRIPT}}", plistEscape(script))
	if err := os.WriteFile(filepath.Join(contents, "document.wflow"), []byte(doc), 0o644); err != nil {
		return "", err
	}
	return root, nil
}

func plistEscape(s string) string {
	return strings.NewReplacer("&", "&amp;", "<", "&lt;", ">", "&gt;").Replace(s)
}

